export function getEntity(ticker: string): Entity | undefined {
  return ENTITY_REGISTRY.find((e) => e.ticker === ticker);
}

export function getCoreEntities(): Entity[] {
  return ENTITY_REGISTRY.filter((e) => e.isCore);
}

export function getSectors(): Array<{ id: string; count: number }> {
  const counts = new Map<string, number>();
  for (const e of ENTITY_REGISTRY) {
    for (const s of e.sectorTags) counts.set(s, (counts.get(s) ?? 0) + 1);
  }
  return Array.from(counts, ([id, count]) => ({ id, count })).sort((a, b) =>
    b.count - a.count,
  );
}

export function getEntitiesInSector(sectorId: string): Entity[] {
  return ENTITY_REGISTRY.filter((e) => e.sectorTags.includes(sectorId));
}
